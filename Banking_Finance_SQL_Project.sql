-- 1. Mumbai branch has highest deposits

select Branch_city,SUM(Acc_balance) as total_deposits from 
Accounts a join Branches b on a.branch_id = b.branch_id
group by Branch_city
order by total_deposits desc;


-- 2. Savings accounts dominate customer base             

select Acc_Type,
       COUNT(*) as total_accounts,
       COUNT(distinct Cust_Id) as unique_customers
from Accounts
group by Acc_Type
order by total_accounts desc;


-- 3. Few customers hold majority of bank balance

select c.Cust_Id,c.Cust_Name,
       SUM(a.Acc_Balance) as total_balance from 
       Customers c join Accounts a on c.Cust_Id = a.Cust_Id
group by c.Cust_Id, c.Cust_Id
order by total_balance desc
limit 10;

-- 4. Loan penetration is low → cross-sell opportunity             

SELECT
    COUNT(DISTINCT c.Cust_Id) AS total_customers,
    COUNT(DISTINCT l.Cust_Id) AS customers_with_loans,
    COUNT(DISTINCT c.Cust_Id)
        - COUNT(DISTINCT l.Cust_Id) AS customers_without_loans,
    ROUND(
        COUNT(DISTINCT l.Cust_Id) * 100.0 /
        COUNT(DISTINCT c.Cust_Id),
        2
    ) AS loan_penetration_pct
FROM Customers c
LEFT JOIN Loans l
    ON c.Cust_Id = l.Cust_Id;

    
-- 5. Transaction activity peaks early in year               

SELECT
    MONTH(Trans_Date) AS month_number,
    MONTHNAME(Trans_Date) AS month_name,
    COUNT(*) AS total_transactions,
    SUM(Trans_Amount) AS total_transaction_amount
FROM Transactions
GROUP BY
    MONTH(Trans_Date),
    MONTHNAME(Trans_Date)
ORDER BY total_transactions DESC;